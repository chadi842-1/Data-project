"""End-to-end pipeline: generate -> ETL -> train -> validate rankings -> demo -> results report.

    python -m invest_agents.pipeline [--root DIR] [--n 2000] [--n-iter 20] [--seed 42]

Writes data/ and artifacts/ (regenerable, gitignored) and reports/ (small, committed):
metrics.json, ranking_validation.json, workflow_demo.json, ahp.json, run_config.json,
etl_report.json, figures and an auto-generated results.md.
"""
from __future__ import annotations

import argparse
import json
from dataclasses import asdict

import numpy as np
import pandas as pd
from scipy import stats

from .agents import run_workflow
from .config import CRITERIA, FEATURES, SEED, Paths, get_paths
from .data import generate_projects, latent_utility
from .etl import run_etl
from .mcda import default_ahp, topsis_scores
from .modeling import run_training
from .scoring import Scorer


def ranking_validation(
    paths: Paths | None = None,
    nonlinearity: float = 1.0,
    n_pools: int = 200,
    pool_size: int = 12,
    seed: int = SEED,
) -> dict:
    """Compare TOPSIS and the ML probability with the TRUE committee utility.

    Only possible because the data is synthetic: the noise-free latent utility is the ground
    truth. For random pools of `pool_size` held-out projects we report the Spearman correlation
    of each ranking with the truth, and the true rank of each method's top pick (1 = best;
    picking at random would give (pool_size + 1) / 2 on average).
    """
    paths = paths or get_paths()
    df = pd.read_csv(paths.data / "test.csv").dropna(subset=FEATURES).reset_index(drop=True)
    if len(df) < pool_size:
        raise ValueError(f"only {len(df)} complete test projects, need {pool_size}")
    df["proba"] = Scorer.load(paths).predict_proba(df)
    df["oracle"] = latent_utility(df, nonlinearity)
    weights = default_ahp().weights
    w = np.array([weights[f] for f in FEATURES])
    sign = np.array([CRITERIA[f] for f in FEATURES])
    rng = np.random.default_rng(seed)

    def rho(a, b) -> float:
        return float(stats.spearmanr(a, b)[0])

    rows = []
    for _ in range(n_pools):
        pool = df.iloc[rng.choice(len(df), pool_size, replace=False)]
        s = topsis_scores(pool[FEATURES].to_numpy(float), w, sign)
        p, o = pool["proba"].to_numpy(), pool["oracle"].to_numpy()
        true_rank = (-o).argsort().argsort() + 1
        rows.append({
            "topsis_vs_truth": rho(s, o),
            "ml_vs_truth": rho(p, o),
            "topsis_vs_ml": rho(s, p),
            "topsis_pick_true_rank": int(true_rank[np.argmax(s)]),
            "ml_pick_true_rank": int(true_rank[np.argmax(p)]),
        })
    r = pd.DataFrame(rows)
    summary = {c: {"mean": round(float(r[c].mean()), 3),
                   "p05": round(float(r[c].quantile(0.05)), 3),
                   "p95": round(float(r[c].quantile(0.95)), 3)} for c in r}
    return {"n_pools": n_pools, "pool_size": pool_size, "nonlinearity": nonlinearity,
            "chance_pick_rank": (pool_size + 1) / 2, **summary}


def workflow_demo(paths: Paths, n: int = 12) -> dict:
    scorer = Scorer.load(paths)
    df = pd.read_csv(paths.data / "test.csv").dropna(subset=FEATURES).head(n)
    cols = ["project_id", *FEATURES]
    return run_workflow(df[cols].to_dict("records"), scorer=scorer).model_dump()


# --------------------------------------------------------------------------- results.md
def _ci(v) -> str:
    return f"[{v[0]:.3f}, {v[1]:.3f}]"


def render_results(paths: Paths) -> str:
    """Build reports/results.md from the JSON files (so numbers are never typed by hand)."""
    rep = paths.reports
    metrics = json.loads((rep / "metrics.json").read_text())
    etl = json.loads((rep / "etl_report.json").read_text())
    val = json.loads((rep / "ranking_validation.json").read_text())
    ahp = json.loads((rep / "ahp.json").read_text())
    cfg = json.loads((rep / "run_config.json").read_text())
    shap_imp = pd.read_csv(rep / "shap_importance.csv", index_col=0).iloc[:, 0]
    perm_imp = pd.read_csv(rep / "permutation_importance.csv", index_col=0).iloc[:, 0]
    st = metrics["settings"]

    L = ["# Results", "",
         "Auto-generated by `python -m invest_agents.pipeline`. Synthetic data: these numbers "
         "describe the simulation, not real-world performance.", "",
         f"Run: seed {cfg['seed']}, nonlinearity {cfg['nonlinearity']}, {cfg['n']} projects.", "",
         "## Data and ETL", "",
         f"- Raw rows: {etl['n_raw']}; duplicates dropped: {etl['n_duplicates_dropped']}; "
         f"schema rejections: {etl['n_schema_rejected']}; clean projects: {etl['n_final']}.",
         f"- Stratified split: {etl['split_sizes']['train']} train / {etl['split_sizes']['val']} "
         f"validation / {etl['split_sizes']['test']} test "
         f"(invest rate {etl['invest_rate']['train']:.2f} / {etl['invest_rate']['val']:.2f} / "
         f"{etl['invest_rate']['test']:.2f}).",
         "- Missing values (share): "
         + ", ".join(f"{k} {v:.1%}" for k, v in etl["missing_rate"].items() if v > 0) + ".", "",
         "## Models", "",
         f"Randomized search, {st['n_iter']} candidates x {st['cv_folds']}-fold CV on train "
         f"(log-loss); F1 threshold chosen on validation; test used once; "
         f"{st['n_boot']} bootstrap resamples.", "",
         "| Model | CV log-loss | Val F1 | Test F1 [95% CI] | Test AUC | Brier | "
         "ΔF1 vs baseline [95% CI] | P(better) |",
         "|---|---|---|---|---|---|---|---|"]
    for name, r in metrics["models"].items():
        t = r["test"]
        d = r.get("f1_diff_vs_baseline")
        diff = f"{d['mean']:+.3f} {_ci(d['ci95'])}" if d else "baseline"
        pb = f"{d['p_better']:.2f}" if d else "-"
        L.append(f"| {name} | {r['cv_log_loss']:.3f} | {r['val_f1']:.3f} | {t['f1']:.3f} "
                 f"{_ci(r['test_f1_ci95'])} | {t['auc']:.3f} | {t['brier']:.3f} | {diff} | {pb} |")
    L += ["", f"**Selected: {metrics['best_model']}.** {metrics['selection_reason']}.", "",
          "A model is only better than the baseline if the interval for its F1 difference "
          "excludes 0. Intervals that straddle 0 are noise at this test size.", "",
          "![Model comparison](model_comparison.png)", "",
          "## What drives the decision", "",
          "| Criterion | Mean abs SHAP | AUC drop when shuffled |", "|---|---|---|"]
    for f in shap_imp.index:
        L.append(f"| {f} | {shap_imp[f]:.3f} | {perm_imp[f]:.3f} |")
    L += ["", "![Feature importance](feature_importance.png)", "",
          "## Ranking validation against the true utility", "",
          f"Over {val['n_pools']} random pools of {val['pool_size']} held-out projects. The truth "
          "is the noise-free committee utility from the data generator, available only because "
          "the data is synthetic.", "",
          "| Measure | Mean | 5th-95th percentile |", "|---|---|---|"]
    labels = {"topsis_vs_truth": "Spearman: AHP+TOPSIS vs truth",
              "ml_vs_truth": "Spearman: ML P(invest) vs truth",
              "topsis_vs_ml": "Spearman: AHP+TOPSIS vs ML P(invest)",
              "topsis_pick_true_rank": "True rank of TOPSIS top pick (1 = best)",
              "ml_pick_true_rank": "True rank of ML top pick (1 = best)"}
    for k, label in labels.items():
        L.append(f"| {label} | {val[k]['mean']:.2f} | {val[k]['p05']:.2f} to {val[k]['p95']:.2f} |")
    L += ["", f"A random pick would have true rank {val['chance_pick_rank']:.1f} on average.", "",
          "## AHP weights", "",
          f"Consistency ratio {ahp['consistency_ratio']:.3f} (acceptable below 0.10). "
          "The priorities are illustrative placeholders, not elicited from experts.", "",
          "| Criterion | Weight |", "|---|---|"]
    L += [f"| {k} | {v:.3f} |" for k, v in sorted(ahp["weights"].items(), key=lambda kv: -kv[1])]
    return "\n".join(L) + "\n"


# --------------------------------------------------------------------------------- run
def run_pipeline(
    paths: Paths | None = None,
    n: int = 2000,
    n_iter: int = 20,
    seed: int = SEED,
    nonlinearity: float = 1.0,
    n_boot: int = 2000,
    cv_folds: int = 5,
    n_jobs: int = -1,
) -> None:
    paths = (paths or get_paths()).ensure()
    print(f"[1/6] generating {n} synthetic projects (nonlinearity={nonlinearity})")
    generate_projects(n=n, seed=seed, nonlinearity=nonlinearity).to_csv(
        paths.data / "projects_raw.csv", index=False)
    print("[2/6] ETL")
    etl = run_etl(paths, seed=seed)
    (paths.reports / "etl_report.json").write_text(json.dumps(asdict(etl), indent=2))
    print("[3/6] training and explaining models")
    run_training(paths, n_iter=n_iter, seed=seed, n_boot=n_boot, cv_folds=cv_folds, n_jobs=n_jobs)
    print("[4/6] validating rankings against the true utility")
    val = ranking_validation(paths, nonlinearity=nonlinearity, seed=seed)
    (paths.reports / "ranking_validation.json").write_text(json.dumps(val, indent=2))
    print("[5/6] agent workflow demo")
    (paths.reports / "workflow_demo.json").write_text(json.dumps(workflow_demo(paths), indent=2))
    ahp = default_ahp()
    (paths.reports / "ahp.json").write_text(json.dumps(
        {"weights": ahp.weights, "consistency_ratio": ahp.consistency_ratio,
         "lambda_max": ahp.lambda_max}, indent=2))
    (paths.reports / "run_config.json").write_text(json.dumps(
        {"n": n, "seed": seed, "nonlinearity": nonlinearity}, indent=2))
    print("[6/6] writing reports/results.md")
    (paths.reports / "results.md").write_text(render_results(paths))
    print(f"done: {paths.reports / 'results.md'}")


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", help="working directory (default: current directory)")
    ap.add_argument("--n", type=int, default=2000, help="number of clean projects")
    ap.add_argument("--n-iter", type=int, default=20, help="random-search candidates per model")
    ap.add_argument("--n-boot", type=int, default=2000, help="bootstrap resamples")
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument("--nonlinearity", type=float, default=1.0)
    a = ap.parse_args(argv)
    run_pipeline(get_paths(a.root), a.n, a.n_iter, a.seed, a.nonlinearity, a.n_boot)


if __name__ == "__main__":
    main()
